//! vgui2 `KeyCode` and `MouseCode` values (docs/re/vgui2-core.md §3.9).

pub type KeyCode = i32;

pub const KEY_NONE: KeyCode = 0;
/// `KEY_0`..`KEY_9` are 1..=10.
pub const KEY_0: KeyCode = 1;
/// `KEY_A`..`KEY_Z` are 11..=36.
pub const KEY_A: KeyCode = 11;
pub const KEY_C: KeyCode = KEY_A + 2;
pub const KEY_V: KeyCode = KEY_A + 21;
pub const KEY_X: KeyCode = KEY_A + 23;
pub const KEY_Z: KeyCode = KEY_A + 25;
/// `KEY_PAD_0`..`KEY_PAD_9` are 37..=46.
pub const KEY_PAD_0: KeyCode = 37;
pub const KEY_PAD_DIVIDE: KeyCode = 47;
pub const KEY_PAD_MULTIPLY: KeyCode = 48;
pub const KEY_PAD_MINUS: KeyCode = 49;
pub const KEY_PAD_PLUS: KeyCode = 50;
pub const KEY_PAD_ENTER: KeyCode = 51;
pub const KEY_PAD_DECIMAL: KeyCode = 52;
pub const KEY_LBRACKET: KeyCode = 53;
pub const KEY_RBRACKET: KeyCode = 54;
pub const KEY_SEMICOLON: KeyCode = 55;
pub const KEY_APOSTROPHE: KeyCode = 56;
pub const KEY_BACKQUOTE: KeyCode = 57;
pub const KEY_COMMA: KeyCode = 58;
pub const KEY_PERIOD: KeyCode = 59;
pub const KEY_SLASH: KeyCode = 60;
pub const KEY_BACKSLASH: KeyCode = 61;
pub const KEY_MINUS: KeyCode = 62;
pub const KEY_EQUAL: KeyCode = 63;
pub const KEY_ENTER: KeyCode = 64;
pub const KEY_SPACE: KeyCode = 65;
pub const KEY_BACKSPACE: KeyCode = 66;
pub const KEY_TAB: KeyCode = 67;
pub const KEY_CAPSLOCK: KeyCode = 68;
pub const KEY_NUMLOCK: KeyCode = 69;
pub const KEY_ESCAPE: KeyCode = 70;
pub const KEY_SCROLLLOCK: KeyCode = 71;
pub const KEY_INSERT: KeyCode = 72;
pub const KEY_DELETE: KeyCode = 73;
pub const KEY_HOME: KeyCode = 74;
pub const KEY_END: KeyCode = 75;
pub const KEY_PAGEUP: KeyCode = 76;
pub const KEY_PAGEDOWN: KeyCode = 77;
pub const KEY_BREAK: KeyCode = 78;
pub const KEY_LSHIFT: KeyCode = 79;
pub const KEY_RSHIFT: KeyCode = 80;
pub const KEY_LALT: KeyCode = 81;
pub const KEY_RALT: KeyCode = 82;
pub const KEY_LCONTROL: KeyCode = 83;
pub const KEY_RCONTROL: KeyCode = 84;
pub const KEY_LWIN: KeyCode = 85;
pub const KEY_RWIN: KeyCode = 86;
pub const KEY_APP: KeyCode = 87;
pub const KEY_UP: KeyCode = 88;
pub const KEY_LEFT: KeyCode = 89;
pub const KEY_DOWN: KeyCode = 90;
pub const KEY_RIGHT: KeyCode = 91;
/// `KEY_F1`..`KEY_F12` are 92..=103.
pub const KEY_F1: KeyCode = 92;
pub const KEY_F4: KeyCode = KEY_F1 + 3;
pub const KEY_F5: KeyCode = KEY_F1 + 4;
pub const KEY_CAPSLOCKTOGGLE: KeyCode = 104;
pub const KEY_NUMLOCKTOGGLE: KeyCode = 105;
pub const KEY_SCROLLLOCKTOGGLE: KeyCode = 106;
/// Codes above this are ignored by the input system.
pub const KEY_LAST: KeyCode = 107;

pub type MouseCode = i32;
pub const MOUSE_LEFT: MouseCode = 0;
pub const MOUSE_RIGHT: MouseCode = 1;
pub const MOUSE_MIDDLE: MouseCode = 2;
pub const MOUSE_4: MouseCode = 3;
pub const MOUSE_5: MouseCode = 4;
pub const MOUSE_LAST: MouseCode = 5;
